"""Add / remove agents at runtime.

A "web agent" is a PJSIP endpoint (WebRTC, ext 12xx) that logs in with the browser softphone (SIP.js).
The registry (data/agents.json) is rendered to pjsip_agents.conf, which the PBX includes
(`#tryinclude /etc/asterisk-dyn/pjsip_agents.conf`) and reloads through AMI (`module reload res_pjsip.so`).
"""
import json
import logging
import re
from pathlib import Path

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

from . import config
from .demo import auth
from .labels import QUEUES

log = logging.getLogger("agents-admin")
router = APIRouter(prefix="/demo/agents", tags=["agents-admin"])
EXT_RANGE = range(1201, 1300)
ami = None


def init(ami_service) -> None:
    global ami
    ami = ami_service


def _reg_path() -> Path:
    return Path(config.DATA_DIR) / "agents.json"


def load() -> list[dict]:
    try:
        return json.loads(_reg_path().read_text())
    except (OSError, ValueError):
        return []


def _save(agents: list[dict]) -> None:
    _reg_path().parent.mkdir(parents=True, exist_ok=True)
    _reg_path().write_text(json.dumps(agents, ensure_ascii=False, indent=1))
    out = Path(config.PBX_DYN_DIR)
    out.mkdir(parents=True, exist_ok=True)
    (out / "pjsip_agents.conf").write_text(render(agents))


def render(agents: list[dict]) -> str:
    lines = ["; generated by the API (agents_admin.py) - do not edit"]
    for a in agents:
        e = a["ext"]
        lines += [
            f"[{e}](webrtc-endpoint)", f"auth={e}", f"aors={e}", f'callerid="{a["name"]}" <{e}>',
            f"[{e}](auth-tpl)", f"username={e}", f"password={a['password']}",
            f"[{e}](webrtc-aor)", "",
        ]
    return "\n".join(lines)


async def _reload() -> None:
    await ami.action({"Action": "Command", "Command": "module reload res_pjsip.so"})


async def sync() -> None:
    """Called at API start: make sure the PBX file matches the registry."""
    try:
        _save(load())
    except OSError as exc:
        log.warning("cannot write pjsip_agents.conf: %s", exc)


class NewAgent(BaseModel):
    name: str | None = None
    ext: str | None = None
    login: bool = True      # join all six queues right away


def _public(a: dict) -> dict:
    return {"extension": a["ext"], "name": a["name"], "password": a["password"]}


@router.get("/registry", dependencies=auth)
async def registry():
    return [_public(a) for a in load()]


@router.post("", dependencies=auth)
async def create(body: NewAgent):
    agents = load()
    used = {a["ext"] for a in agents}
    if body.ext:
        if not re.fullmatch(r"12\d\d", body.ext) or int(body.ext) not in EXT_RANGE:
            raise HTTPException(422, "extension must be 1201-1299")
        ext = body.ext
    else:
        ext = next((str(x) for x in EXT_RANGE if str(x) not in used), None)
        if not ext:
            raise HTTPException(409, "no free extension")
    if ext in used:
        raise HTTPException(409, f"agent {ext} already exists")
    agent = {"ext": ext, "name": (body.name or f"Agent {ext}").replace('"', "")[:40], "password": f"poc-{ext}"}
    agents.append(agent)
    _save(agents)
    await _reload()
    if body.login:
        for q in QUEUES:
            await ami.action({"Action": "QueueAdd", "Queue": q, "Interface": f"PJSIP/{ext}", "MemberName": agent["name"]})
    return _public(agent)


@router.delete("/{ext}", dependencies=auth)
async def delete(ext: str):
    agents = load()
    if not any(a["ext"] == ext for a in agents):
        raise HTTPException(404, "only agents created through this API can be removed")
    for q in QUEUES:
        await ami.action({"Action": "QueueRemove", "Queue": q, "Interface": f"PJSIP/{ext}"})
    try:                                    # drop a call in progress, if any
        await ami.action({"Action": "Hangup", "Channel": f"/^PJSIP\\/{ext}-/", "Cause": "16"})
    except Exception:
        pass
    _save([a for a in agents if a["ext"] != ext])
    await _reload()
    return {"removed": ext}
